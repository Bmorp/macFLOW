import AppKit
import SwiftUI
import Combine

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    var id = UUID()
    var kind: Kind = .text
    var text: String
    var date: Date
    var pinned = false
    var appBundleID: String?
    var imageFile: String?          // PNG in Application Support/Atoll/clips
    var filePaths: [String]?
    var imageSize: CGSize?

    init(text: String, date: Date, pinned: Bool = false, appBundleID: String? = nil) {
        self.text = text
        self.date = date
        self.pinned = pinned
        self.appBundleID = appBundleID
    }

    /// Tolerant decoding so history saved by earlier versions keeps loading.
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decodeIfPresent(UUID.self, forKey: .id) ?? UUID()
        kind = try c.decodeIfPresent(Kind.self, forKey: .kind) ?? .text
        text = try c.decodeIfPresent(String.self, forKey: .text) ?? ""
        date = try c.decodeIfPresent(Date.self, forKey: .date) ?? Date()
        pinned = try c.decodeIfPresent(Bool.self, forKey: .pinned) ?? false
        appBundleID = try c.decodeIfPresent(String.self, forKey: .appBundleID)
        imageFile = try c.decodeIfPresent(String.self, forKey: .imageFile)
        filePaths = try c.decodeIfPresent([String].self, forKey: .filePaths)
        imageSize = try c.decodeIfPresent(CGSize.self, forKey: .imageSize)
    }

    // Smart detection
    enum Flavor { case plain, link, color, code, email, number, image, files }

    var flavor: Flavor {
        switch kind {
        case .image: return .image
        case .files: return .files
        case .text: break
        }
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if Self.color(from: t) != nil { return .color }
        if !t.contains(" "), let u = URL(string: t), let s = u.scheme, ["http", "https"].contains(s), u.host != nil { return .link }
        if t.range(of: #"^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$"#, options: [.regularExpression, .caseInsensitive]) != nil { return .email }
        if Double(t.replacingOccurrences(of: ",", with: "")) != nil { return .number }
        let codeHints = ["{", "};", "()", "=>", "func ", "def ", "const ", "let ", "import ", "#include", "</", "$ ", "sudo ", "git "]
        if codeHints.contains(where: t.contains) || t.hasPrefix("#!") { return .code }
        return .plain
    }

    var url: URL? { flavor == .link ? URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)) : nil }

    static func color(from s: String) -> Color? {
        let t = s.trimmingCharacters(in: .whitespaces)
        if t.range(of: #"^#?[0-9a-fA-F]{6}$"#, options: .regularExpression) != nil { return Color(hex: t) }
        if let m = try? NSRegularExpression(pattern: #"^rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})"#)
            .firstMatch(in: t, range: NSRange(t.startIndex..., in: t)) {
            let comps = (1...3).compactMap { Range(m.range(at: $0), in: t).flatMap { Double(t[$0]) } }
            if comps.count == 3 { return Color(red: comps[0] / 255, green: comps[1] / 255, blue: comps[2] / 255) }
        }
        return nil
    }
}

/// Clipboard history: text, images and file copies. Skips anything password managers mark as concealed.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    @Published private(set) var items: [ClipItem] = []

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let maxItems = 60
    private let maxImages = 20
    private let fileName = "clipboard.json"
    private let imageDir: URL = {
        let d = Storage.directory.appendingPathComponent("clips", isDirectory: true)
        try? FileManager.default.createDirectory(at: d, withIntermediateDirectories: true)
        return d
    }()
    private let imageCache = NSCache<NSString, NSImage>()
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "com.apple.is-remote-clipboard",
    ]

    private var prefWatch: AnyCancellable?

    init() {
        items = Storage.load([ClipItem].self, from: fileName) ?? []
        // Poll only while history is on (the pasteboard has no change notification).
        prefWatch = Prefs.shared.$clipboardEnabled
            .removeDuplicates()
            .sink { [weak self] on in self?.setPolling(on) }
    }

    private func setPolling(_ on: Bool) {
        if on, timer == nil {
            lastChange = NSPasteboard.general.changeCount
            let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
            t.tolerance = 0.25
            RunLoop.main.add(t, forMode: .common)
            timer = t
        } else if !on {
            timer?.invalidate()
            timer = nil
        }
    }

    // MARK: - Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard Prefs.shared.clipboardEnabled else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            var item = ClipItem(text: urls.map(\.lastPathComponent).joined(separator: ", "), date: Date(), appBundleID: app)
            item.kind = .files
            item.filePaths = urls.map(\.path)
            insert(item, matching: { $0.kind == .files && $0.filePaths == item.filePaths })
            return
        }
        if let raw = pb.string(forType: .string) {
            // Cap first: a multi-megabyte log copied from a terminal shouldn't be walked character by character
            // (String.count and trimming both do) on the main thread.
            let text = raw.utf16.count > 20_000 ? String(raw.prefix(20_000)) : raw
            guard text.contains(where: { !$0.isWhitespace }) else { return }
            insert(ClipItem(text: text, date: Date(), appBundleID: app), matching: { $0.kind == .text && $0.text == text })
            return
        }
        if Prefs.shared.clipboardImages, let image = NSImage(pasteboard: pb), image.isValid {
            saveImage(image, app: app)
        }
    }

    /// Downscales and PNG-encodes off the main thread (a screenshot is tens of megapixels), then records it.
    private func saveImage(_ image: NSImage, app: String?) {
        let original = image.size
        guard let source = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return }
        let url = imageDir.appendingPathComponent("\(UUID().uuidString).png")
        let job = UncheckedImage(cg: source)
        DispatchQueue.global(qos: .utility).async { [weak self] in
            guard let png = Self.encodePNG(job.cg, maxSide: 1600), (try? png.write(to: url)) != nil else { return }
            DispatchQueue.main.async {
                guard let self else { return }
                var item = ClipItem(text: "Image \(Int(original.width))×\(Int(original.height))", date: Date(), appBundleID: app)
                item.kind = .image
                item.imageFile = url.lastPathComponent
                item.imageSize = original
                self.insert(item, matching: { _ in false })
            }
        }
    }

    private struct UncheckedImage: @unchecked Sendable { let cg: CGImage }

    nonisolated private static func encodePNG(_ image: CGImage, maxSide: CGFloat) -> Data? {
        var w = CGFloat(image.width), h = CGFloat(image.height)
        if max(w, h) > maxSide {
            let s = maxSide / max(w, h)
            w = (w * s).rounded()
            h = (h * s).rounded()
        }
        guard let ctx = CGContext(data: nil, width: Int(w), height: Int(h), bitsPerComponent: 8, bytesPerRow: 0,
                                  space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        ctx.interpolationQuality = .high
        ctx.draw(image, in: CGRect(x: 0, y: 0, width: w, height: h))
        guard let scaled = ctx.makeImage() else { return nil }
        return NSBitmapImageRep(cgImage: scaled).representation(using: .png, properties: [:])
    }

    private func insert(_ item: ClipItem, matching: (ClipItem) -> Bool) {
        var new = item
        if let idx = items.firstIndex(where: matching) {
            new.pinned = items[idx].pinned
            new.imageFile = new.imageFile ?? items[idx].imageFile
            items.remove(at: idx)
        }
        withAnimation(.spring(response: 0.35, dampingFraction: 0.85)) {
            items.insert(new, at: 0)
            trim()
        }
        save()
    }

    private func trim() {
        var unpinned = 0, images = 0
        var removed: [ClipItem] = []
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            if item.kind == .image { images += 1 }
            let keep = unpinned <= maxItems && (item.kind != .image || images <= maxImages)
            if !keep { removed.append(item) }
            return keep
        }
        removed.forEach(deleteImageFile)
    }

    // MARK: - Actions

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = imageCache.object(forKey: name as NSString) { return cached }
        guard let img = NSImage(contentsOf: imageDir.appendingPathComponent(name)) else { return nil }
        imageCache.setObject(img, forKey: name as NSString)
        return img
    }

    /// Puts the item back on the clipboard. Returns true if it was also pasted into the front app.
    @discardableResult
    func use(_ item: ClipItem, paste: Bool) -> Bool {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text, forType: .string)
        case .image:
            if let img = image(for: item) { pb.writeObjects([img]) }
        case .files:
            pb.writeObjects((item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        lastChange = pb.changeCount
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: idx)
            moved.date = Date()
            withAnimation(.spring(response: 0.35, dampingFraction: 0.85)) { items.insert(moved, at: 0) }
        }
        save()
        guard paste, InputControl.isTrusted else { return false }
        IslandManager.shared.collapseAll()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) { InputControl.pasteIntoFrontApp() }
        return true
    }

    func togglePin(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        withAnimation(.spring(response: 0.3, dampingFraction: 0.8)) { items[idx].pinned.toggle() }
        save()
    }

    func delete(_ item: ClipItem) {
        deleteImageFile(item)
        withAnimation(.spring(response: 0.3, dampingFraction: 0.85)) { items.removeAll { $0.id == item.id } }
        save()
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(deleteImageFile)
        withAnimation(.spring(response: 0.35, dampingFraction: 0.85)) { items.removeAll { !$0.pinned } }
        save()
    }

    private func deleteImageFile(_ item: ClipItem) {
        guard let name = item.imageFile, !Storage.readOnly else { return }
        try? FileManager.default.removeItem(at: imageDir.appendingPathComponent(name))
        imageCache.removeObject(forKey: name as NSString)
    }

    private func save() { Storage.save(items, to: fileName) }

    #if DEBUG
    func debugReplace(_ demo: [ClipItem]) { items = demo }
    #endif

    static func appIcon(for bundleID: String?) -> NSImage? { IconCache.app(bundleID: bundleID) }
}
